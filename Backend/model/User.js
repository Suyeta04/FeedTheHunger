const mongoose = require('mongoose');

const dataSchema = new mongoose.Schema({
    name: {
        required: true,
        type: String
    },
    email: {
        required: true,
        type: String
    },
    password: {
        required: true,
        type: String
    },
    contact: {
        required: true,
        type: String
    }
});

// ✅ Prevent model overwrite during dev hot reload
module.exports = mongoose.models.User || mongoose.model('User', dataSchema);
